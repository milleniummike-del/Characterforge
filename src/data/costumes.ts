/**
 * Returns 5 full outfit ensembles tailored to any character by genre, role, and name.
 */
export function getCharacterFiveEnsembles(
  genre: GenreType,
  role: string,
  characterName?: string
): CharacterOutfitEnsemble[] {
  // Check exact preset character name first
  if (characterName && PRESET_CHARACTER_ENSEMBLES[characterName]) {
    return PRESET_CHARACTER_ENSEMBLES[characterName];
  }

  // Check matching preset name substring
  if (characterName) {
    for (const key of Object.keys(PRESET_CHARACTER_ENSEMBLES)) {
      if (characterName.toLowerCase().includes(key.toLowerCase()) || key.toLowerCase().includes(characterName.toLowerCase())) {
        return PRESET_CHARACTER_ENSEMBLES[key];
      }
    }
  }

  // Base 5 ensembles from the genre
  const genreEnsembles = GENRE_FIVE_ENSEMBLES[genre] || GENRE_FIVE_ENSEMBLES.Action;

  // Personalize each of the 5 ensembles with the specific role archetype
  return genreEnsembles.map((ens) => ({
    ...ens,
    id: `${genre.toLowerCase()}-${role.toLowerCase().replace(/[^a-z0-9]/g, '-')}-${ens.themeType}`,
    label: `${ens.label} (${role})`,
    description: `${ens.description} tailored for ${role}`,
  }));
}

